import '../config/app_config.dart';

/// In-app legal copy (Hebrew, RTL).
///
/// NOTE: This is a starting-point draft for closed beta, not final legal
/// text. `companyName`/`contactEmail` are sourced from [AppConfig] (build-time
/// `--dart-define`s) instead of hardcoded placeholders, so a real deploy can
/// set them without a code change — but the copy itself still needs legal
/// review before a public launch. The canonical Markdown source lives in
/// `docs/legal/`.
abstract final class LegalContent {
  const LegalContent._();

  static const companyName = AppConfig.companyLegalName;

  static String get contactEmail => AppConfig.hasSupportEmail
      ? AppConfig.supportEmail
      : 'כתובת תמיכה תפורסם בקרוב — עד אז ניתן לפנות דרך מנהל המערכת שהזמין אותך';

  static const lastUpdated = 'טיוטת בטא — טרם אושרה סופית';

  static const betaDraftNotice =
      'מסמך זה הוא טיוטת בטא סגורה בלבד ואינו סופי. הנוסח המחייב יפורסם לפני '
      'השקה ציבורית ולאחר בדיקה משפטית.';

  static String get privacyPolicy => '''
מדיניות פרטיות

$lastUpdated
$betaDraftNotice

מסמך זה מתאר כיצד $companyName ("אנחנו") אוספת, משתמשת ושומרת מידע במסגרת השימוש
באפליקציית "בקשות הצעת מחיר" ("השירות"). זוהי טיוטה ראשונית הדורשת בדיקה משפטית
לפני פרסום.

1. מידע שאנו אוספים
• פרטי חשבון: כתובת דוא"ל, שם מלא, טלפון ועיר שנמסרים בעת ההרשמה ובפרופיל.
• תוכן שנוצר בשירות: בקשות להצעות מחיר, הצעות מחיר, פרטי פריטים, הזמנות ומשלוחים.
• נתוני שימוש טכניים: מזהי מכשיר בסיסיים ולוגים תפעוליים הדרושים לתפעול השירות.

2. כיצד אנו משתמשים במידע
• לספק את השירות, לנהל הרשאות ולחבר בין מזמינים לספקים.
• לשפר את חוויית המשתמש, לאבטח את המערכת ולמנוע שימוש לרעה.
• לצורך תקשורת תפעולית הנוגעת לחשבון ולבקשות.

3. שיתוף מידע וספקי משנה
המידע מאוחסן ומעובד באמצעות שירותי Google Firebase (אימות, בסיס נתונים ואחסון).
איננו מוכרים מידע אישי. שיתוף עם צדדים שלישיים נעשה רק כנדרש לתפעול השירות או על פי
דין.

4. שמירת מידע
מידע נשמר כל עוד החשבון פעיל וכנדרש למטרות תפעוליות ומשפטיות.

5. זכויותיך
ניתן לבקש עיון, תיקון או מחיקה של מידע אישי בפנייה אל $contactEmail.

6. אבטחה
אנו נוקטים באמצעים סבירים להגנה על המידע, אך אין העברה או אחסון החסינים לחלוטין.

7. יצירת קשר
לשאלות בנושא פרטיות: $contactEmail.
''';

  static String get termsOfService => '''
תנאי שימוש

$lastUpdated

תנאים אלה מסדירים את השימוש באפליקציית "בקשות הצעת מחיר" ("השירות") המופעלת על ידי
$companyName. זוהי טיוטה ראשונית הדורשת בדיקה משפטית לפני פרסום.

1. קבלת התנאים
השימוש בשירות מהווה הסכמה לתנאים אלה ולמדיניות הפרטיות.

2. חשבונות והרשאות
• עליך למסור מידע נכון ולשמור על סודיות פרטי ההתחברות.
• הגישה לתכונות מסוימות מותנית באישור ובהרשאות המתאימות בארגון.

3. שימוש מותר
אין להשתמש בשירות למטרה בלתי חוקית, להעלות תוכן מפר או לפגוע בפעילות המערכת או
במשתמשים אחרים.

4. תוכן משתמשים
אתה אחראי לתוכן שאתה מזין (בקשות, הצעות, פרטי פריטים) ולנכונותו. בקשות והצעות מחיר
מהוות מידע עסקי בין הצדדים ואינן ערובה להתקשרות.

5. זמינות ואחריות
השירות ניתן כמות שהוא ("AS IS"). איננו מתחייבים לזמינות רציפה ואיננו אחראים לנזקים
עקיפים הנובעים מהשימוש, בכפוף לדין החל.

6. שינויים
אנו רשאים לעדכן תנאים אלה מעת לעת; המשך השימוש מהווה הסכמה לגרסה המעודכנת.

7. יצירת קשר
לשאלות בנושא התנאים: $contactEmail.
''';
}
